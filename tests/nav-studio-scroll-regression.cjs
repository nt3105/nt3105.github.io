'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const studio=fs.readFileSync('python-studio.html','utf8');
const css=fs.readFileSync('appearance.css','utf8');
const script=fs.readFileSync('script.js','utf8');
assert(html.includes('src="python-studio.html?embed=1&amp;v=nav-code-fix-2"'), 'Website must load the fixed Python Studio and bypass old cache');
assert(html.includes('appearance.css?v=nav-code-fix-2'), 'Website must load corrected navigation styles bypassing old cache');
assert(html.includes('href="#donate"'), 'Donation navigation link must exist');
assert(html.includes('href="#code-corner"'), 'Original Code Corner shortcut must remain');
assert(!studio.includes('active.scrollIntoView('), 'Auto-running Code Studio must not scroll its parent document');
assert(!/\.scrollIntoView\s*\(/.test(studio),'Code Studio must never call scrollIntoView in its timer');
assert(studio.includes('editor.scrollTop+=row.bottom-box.bottom+16'), 'Editor must internally scroll to the active line');
assert(studio.includes('editor.scrollTop+=row.top-box.top-16'), 'Editor must scroll internally to earlier lines');
assert(studio.includes('renderCode(shown,true)'), 'Animated typing must be preserved');
assert(studio.includes('async function execute('), 'Code execution simulation must be preserved');
assert(studio.includes("type: 'ntjr:python-studio-height'"), 'Iframe auto-height messages must be preserved');
assert(studio.includes('window.parent.scrollBy'), 'User-initiated iframe wheel forwarding must be preserved');
assert(css.includes('grid-template-columns:repeat(5,max-content); justify-content:center'), 'Desktop menu must have five compact real columns');
assert(css.includes('#header #nav-links { grid-template-columns:repeat(4,minmax(0,1fr))'), 'Mobile nav must reserve four columns');
assert(css.includes('[href="#personal-space"]) { display:none; }'),'Hide Personal on mobile, but do not hide Donation');
assert(!css.includes('[href="#donate"]) { display:none; }'), 'Do not hide Donation link');
assert(css.includes('flex:0 0 calc((100% - 16px) / 5)'), 'Five equal compact slots on mobile including appearance toggle');
assert(script.includes('function paintNavSelection()'), 'Original sliding selection effect must be kept');
assert(script.includes('window.addEventListener(\'pageshow\''), 'Original page restoration listener must remain');
assert(script.includes('navPending = navSections.find('), 'Click-intent scroll logic must remain');
const navMarkup=html.slice(html.indexOf('id="nav-links"'),html.indexOf('</nav>'));
const nav=[...navMarkup.matchAll(/<a href="#(skills|projects|personal-space|donate|contact)"/g)].map(x=>x[1]);
assert.deepEqual(nav,['skills','projects','personal-space','donate','contact'], 'Original links stay intact and in order');
console.log('PASS scroll isolation + original typing, animations and navigation + 4 mobile links including Donate');
